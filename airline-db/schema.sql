CREATE TABLE airport (
    code        VARCHAR(3)   NOT NULL,
    name        VARCHAR(120) NOT NULL,
    city        VARCHAR(80)  NOT NULL,
    country     VARCHAR(80)  NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_airport PRIMARY KEY (code),
    CONSTRAINT ck_airport_code CHECK (code ~ '^[A-Z]{3}$')
);

CREATE TABLE aircraft (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    aircraft_type VARCHAR(40)  NOT NULL,
    seat_rows     INTEGER      NOT NULL,
    seat_letters  VARCHAR(10)  NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_aircraft PRIMARY KEY (id),
    CONSTRAINT ck_aircraft_seat_rows CHECK (seat_rows BETWEEN 1 AND 100),
    CONSTRAINT ck_aircraft_seat_letters CHECK (seat_letters ~ '^[A-Z]{1,10}$')
);


CREATE TABLE flight_schedule (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    flight_number       VARCHAR(8)  NOT NULL,
    source_airport      VARCHAR(3)  NOT NULL,
    destination_airport VARCHAR(3)  NOT NULL,
    departure_time      TIME        NOT NULL,
    arrival_time        TIME        NOT NULL,
    aircraft_id         BIGINT      NOT NULL,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_flight_schedule PRIMARY KEY (id),
    CONSTRAINT uq_flight_schedule_flight_number UNIQUE (flight_number),
    CONSTRAINT fk_flight_schedule_source FOREIGN KEY (source_airport) REFERENCES airport (code),
    CONSTRAINT fk_flight_schedule_destination FOREIGN KEY (destination_airport) REFERENCES airport (code),
    CONSTRAINT fk_flight_schedule_aircraft FOREIGN KEY (aircraft_id) REFERENCES aircraft (id),
    CONSTRAINT ck_flight_schedule_route CHECK (source_airport <> destination_airport)
);
CREATE INDEX idx_flight_schedule_route ON flight_schedule (source_airport, destination_airport);
CREATE INDEX idx_flight_schedule_aircraft ON flight_schedule (aircraft_id);

CREATE TABLE flight_schedule_day (
    schedule_id BIGINT      NOT NULL,
    day_of_week VARCHAR(9)  NOT NULL,
    CONSTRAINT pk_flight_schedule_day PRIMARY KEY (schedule_id, day_of_week),
    CONSTRAINT fk_flight_schedule_day_schedule FOREIGN KEY (schedule_id) REFERENCES flight_schedule (id) ON DELETE CASCADE,
    CONSTRAINT ck_flight_schedule_day CHECK (day_of_week IN
        ('MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY', 'FRIDAY', 'SATURDAY', 'SUNDAY'))
);

CREATE TABLE flight_instance (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY,
    schedule_id  BIGINT      NOT NULL,
    flight_date  DATE        NOT NULL,
    departure_at TIMESTAMPTZ NOT NULL,
    arrival_at   TIMESTAMPTZ NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_flight_instance PRIMARY KEY (id),
    CONSTRAINT uq_flight_instance_schedule_date UNIQUE (schedule_id, flight_date),
    CONSTRAINT fk_flight_instance_schedule FOREIGN KEY (schedule_id) REFERENCES flight_schedule (id),
    CONSTRAINT ck_flight_instance_times CHECK (arrival_at > departure_at)
);
CREATE INDEX idx_flight_instance_date ON flight_instance (flight_date, departure_at);


CREATE TABLE booking (
    id                  UUID        NOT NULL,
    flight_instance_id  BIGINT      NOT NULL,
    status              VARCHAR(12) NOT NULL,
    passenger_count     INTEGER     NOT NULL,
    cancelled_at        TIMESTAMPTZ,
    version             BIGINT      NOT NULL DEFAULT 0,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT pk_booking PRIMARY KEY (id),
    CONSTRAINT fk_booking_flight_instance FOREIGN KEY (flight_instance_id) REFERENCES flight_instance (id),
    CONSTRAINT ck_booking_status CHECK (status IN ('CONFIRMED', 'CANCELLED')),
    CONSTRAINT ck_booking_passenger_count CHECK (passenger_count > 0)
);
CREATE INDEX idx_booking_flight_instance ON booking (flight_instance_id);

CREATE TABLE booking_seat (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY,
    booking_id          UUID         NOT NULL,
    flight_instance_id  BIGINT       NOT NULL,
    seat_label          VARCHAR(4)   NOT NULL,
    passenger_name      VARCHAR(100) NOT NULL,
    active              BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_booking_seat PRIMARY KEY (id),
    CONSTRAINT fk_booking_seat_booking FOREIGN KEY (booking_id) REFERENCES booking (id),
    CONSTRAINT fk_booking_seat_flight_instance FOREIGN KEY (flight_instance_id) REFERENCES flight_instance (id)
);
CREATE UNIQUE INDEX uq_booking_seat_active ON booking_seat (flight_instance_id, seat_label) WHERE active;
CREATE INDEX idx_booking_seat_booking ON booking_seat (booking_id);


CREATE TABLE shedlock (
    name       VARCHAR(64)  NOT NULL,
    lock_until TIMESTAMPTZ  NOT NULL,
    locked_at  TIMESTAMPTZ  NOT NULL,
    locked_by  VARCHAR(255) NOT NULL,
    CONSTRAINT pk_shedlock PRIMARY KEY (name)
);
